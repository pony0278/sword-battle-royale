import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = path.join(repositoryRoot, 'tools', 'kaykit_combat_lab_v3_procedural_character_generator.html');
const animationOutputDir = path.join(repositoryRoot, 'assets', 'kaykit', 'animations');
const manifestOutputFile = path.join(repositoryRoot, 'assets', 'kaykit', 'manifest.json');
const definitionOutputFile = path.join(repositoryRoot, 'src', 'character', 'kaykit-rig-definition.js');
const animationPacks = [
  { id: 'general', embeddedId: 'general' },
  { id: 'basic', embeddedId: 'basic' },
  { id: 'advanced', embeddedId: 'advanced' },
  { id: 'melee', embeddedId: 'melee' },
  { id: 'ranged' },
  { id: 'simulation' },
  { id: 'special' },
  { id: 'tools' },
];

function readEmbeddedBase64(source, id) {
  const match = source.match(new RegExp(`${id}:"([A-Za-z0-9+/=]+)"`));
  if (!match) throw new Error(`Missing embedded KayKit asset: ${id}`);
  return match[1];
}

function parseGlbJson(buffer) {
  if (buffer.toString('ascii', 0, 4) !== 'glTF') throw new Error('Embedded asset is not a GLB');
  const declaredLength = buffer.readUInt32LE(8);
  if (declaredLength !== buffer.length) {
    throw new Error(`Invalid GLB length: header=${declaredLength}, actual=${buffer.length}`);
  }
  let offset = 12;
  while (offset + 8 <= buffer.length) {
    const chunkLength = buffer.readUInt32LE(offset);
    const chunkType = buffer.readUInt32LE(offset + 4);
    const start = offset + 8;
    if (chunkType === 0x4e4f534a) {
      return JSON.parse(buffer.subarray(start, start + chunkLength).toString('utf8').trim());
    }
    offset = start + chunkLength;
  }
  throw new Error('GLB has no JSON chunk');
}

function nodeTransform(node = {}) {
  if (node.matrix) return { matrix: node.matrix };
  return {
    position: node.translation || [0, 0, 0],
    quaternion: node.rotation || [0, 0, 0, 1],
    scale: node.scale || [1, 1, 1],
  };
}

function createParentIndex(nodes) {
  const parents = new Map();
  nodes.forEach((node, parentIndex) => {
    (node.children || []).forEach((childIndex) => parents.set(childIndex, parentIndex));
  });
  return parents;
}

function nearestJointParent(index, parents, jointIndexes) {
  let parent = parents.get(index);
  while (parent != null && !jointIndexes.has(parent)) parent = parents.get(parent);
  return parent == null ? null : parent;
}

function buildRigDefinition(glb) {
  const skin = [...(glb.skins || [])].sort((a, b) => b.joints.length - a.joints.length)[0];
  if (!skin) throw new Error('KayKit source GLB has no skin');
  const nodes = glb.nodes || [];
  const parents = createParentIndex(nodes);
  const jointIndexes = new Set(skin.joints);
  const depth = (index) => {
    let result = 0;
    let parent = nearestJointParent(index, parents, jointIndexes);
    while (parent != null) {
      result += 1;
      parent = nearestJointParent(parent, parents, jointIndexes);
    }
    return result;
  };
  const bones = [...skin.joints]
    .sort((a, b) => depth(a) - depth(b))
    .map((index) => {
      const node = nodes[index];
      const parentIndex = nearestJointParent(index, parents, jointIndexes);
      return {
        id: node.name,
        parent: parentIndex == null ? null : nodes[parentIndex].name,
        ...nodeTransform(node),
      };
    });

  const boneIds = new Set(bones.map((bone) => bone.id));
  const findBone = (...candidates) => candidates.find((id) => boneIds.has(id));
  const sockets = {
    HAND_L: { parent: findBone('handslot.l', 'hand.l', 'wrist.l'), position: [0, 0, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
    HAND_R: { parent: findBone('handslot.r', 'hand.r', 'wrist.r'), position: [0, 0, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
    HEAD: { parent: findBone('head', 'chest'), position: [0, 0.24, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
    BACK: { parent: findBone('chest', 'spine'), position: [0, 0, -0.18], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
    HIP_L: { parent: findBone('hips', 'root'), position: [-0.18, 0, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
    HIP_R: { parent: findBone('hips', 'root'), position: [0.18, 0, 0], quaternion: [0, 0, 0, 1], scale: [1, 1, 1] },
  };
  for (const [socketId, socket] of Object.entries(sockets)) {
    if (!socket.parent) throw new Error(`Cannot resolve ${socketId} parent bone`);
  }

  return {
    format: 'procedural-humanoid-rig',
    version: 1,
    id: 'kaykit_rig_medium',
    sourceSkeleton: skin.name || 'Rig_Medium',
    bones,
    sockets,
  };
}

function generatedDefinitionModule(definition) {
  return `// Generated by build/extract-kaykit-assets.mjs. Do not edit by hand.\n`+
    `function deepFreeze(value) {\n`+
    `  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n`+
    `  Object.values(value).forEach(deepFreeze);\n`+
    `  return Object.freeze(value);\n`+
    `}\n\n`+
    `export const KAYKIT_RIG_MEDIUM_DEFINITION = deepFreeze(${JSON.stringify(definition, null, 2)});\n`;
}

const source = await readFile(sourceFile, 'utf8');
const knightBuffer = Buffer.from(readEmbeddedBase64(source, 'knight'), 'base64');
const rigDefinition = buildRigDefinition(parseGlbJson(knightBuffer));
const manifest = {
  format: 'kaykit-animation-manifest',
  version: 1,
  rigId: rigDefinition.id,
  source: 'tools/kaykit_combat_lab_v3_procedural_character_generator.html',
  packs: [],
};

await mkdir(animationOutputDir, { recursive: true });
for (const pack of animationPacks) {
  const filename = `${pack.id}.glb`;
  const outputPath = path.join(animationOutputDir, filename);
  const buffer = pack.embeddedId
    ? Buffer.from(readEmbeddedBase64(source, pack.embeddedId), 'base64')
    : await readFile(outputPath);
  const glb = parseGlbJson(buffer);
  if (pack.embeddedId) await writeFile(outputPath, buffer);
  manifest.packs.push({
    id: pack.id,
    file: `animations/${filename}`,
    byteLength: buffer.length,
    clips: (glb.animations || []).map((animation) => animation.name),
  });
}

await mkdir(path.dirname(manifestOutputFile), { recursive: true });
await writeFile(manifestOutputFile, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
await writeFile(definitionOutputFile, generatedDefinitionModule(rigDefinition), 'utf8');

console.log(`Generated ${path.relative(repositoryRoot, definitionOutputFile)} (${rigDefinition.bones.length} bones).`);
console.log(`Extracted ${manifest.packs.length} animation packs with ${manifest.packs.reduce((sum, pack) => sum + pack.clips.length, 0)} clips.`);
