import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entryFile = path.join(repositoryRoot, 'tools', 'action-studio', 'action-studio.js');
const outputFile = path.join(repositoryRoot, 'tools', 'action-studio', 'action-studio.bundle.js');
const htmlTemplateFile = path.join(repositoryRoot, 'tools', 'action-studio', 'index.template.html');
const htmlOutputFile = path.join(repositoryRoot, 'tools', 'action-studio', 'index.html');
const moduleIds = new Map();
const moduleBlocks = [];

function normalizedRelativePath(filename) {
  return path.relative(repositoryRoot, filename).replaceAll(path.sep, '/');
}

function gitBlobVersion(content) {
  const body = Buffer.from(content, 'utf8');
  return createHash('sha1')
    .update(Buffer.from(`blob ${body.length}\0`, 'utf8'))
    .update(body)
    .digest('hex')
    .slice(0, 12);
}

async function compileModule(filename) {
  const absoluteFilename = path.resolve(filename);
  if (moduleIds.has(absoluteFilename)) return moduleIds.get(absoluteFilename);
  const moduleId = `__actionStudioModule${moduleIds.size}`;
  moduleIds.set(absoluteFilename, moduleId);
  let source = await readFile(absoluteFilename, 'utf8');
  const imports = [...source.matchAll(/import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"]\s*;/g)];
  for (const match of imports) {
    const specifier = match[2];
    if (!specifier.startsWith('.')) throw new Error(`${normalizedRelativePath(absoluteFilename)} imports unsupported package ${specifier}`);
    const dependencyFile = path.resolve(path.dirname(absoluteFilename), specifier);
    const dependencyId = await compileModule(dependencyFile);
    const bindings = match[1].split(',').map((name) => name.trim()).filter(Boolean).join(', ');
    source = source.replace(match[0], `const { ${bindings} } = ${dependencyId};`);
  }
  const exportNames = [];
  source = source.replace(/\bexport\s+(const|let|var|function|class)\s+([A-Za-z_$][\w$]*)/g, (_match, kind, name) => {
    exportNames.push(name);
    return `${kind} ${name}`;
  });
  if (/\b(?:import|export)\s/.test(source)) throw new Error(`Unsupported ESM syntax remains in ${normalizedRelativePath(absoluteFilename)}`);
  const block = [
    `// ${normalizedRelativePath(absoluteFilename)}`,
    `const ${moduleId} = (() => {`,
    source.trim(),
    `return Object.freeze({ ${exportNames.join(', ')} });`,
    '})();',
  ].join('\n');
  moduleBlocks.push(block);
  return moduleId;
}

await compileModule(entryFile);
const banner = [
  '/* Action Studio standalone bundle.',
  ' * Generated by: npm run build:action-studio',
  ' * Source of truth remains tools/action-studio/action-studio.js and src/.',
  ' * Runtime parity stage: G2.5.2',
  ' * Classic-script output intentionally supports direct file:// opening.',
  ' */',
].join('\n');
const output = `${banner}\n(() => {\n'use strict';\n${moduleBlocks.join('\n\n')}\n})();\n`;
await writeFile(outputFile, output, 'utf8');
const bundleVersion = gitBlobVersion(output);

const htmlTemplate = await readFile(htmlTemplateFile, 'utf8');
const moduleTag = '<script type="module" src="./action-studio.js"></script>';
const moduleBootstrap = [
  '<script type="module">',
  "    await import('./action-studio.js');",
  "    await import('./studio-combat-feel-controller.js');",
  '  </script>',
].join('\n');
const moduleBootstrapCrlf = moduleBootstrap.split(String.fromCharCode(10)).join(String.fromCharCode(13, 10));
const moduleEntry = htmlTemplate.includes(moduleTag)
  ? moduleTag
  : htmlTemplate.includes(moduleBootstrap)
    ? moduleBootstrap
    : (htmlTemplate.includes(moduleBootstrapCrlf) ? moduleBootstrapCrlf : null);
if (!moduleEntry) throw new Error(`${normalizedRelativePath(htmlTemplateFile)} is missing the expected Action Studio module entry`);

const protocolAwareEntry = [
  '<script>',
  "    window.__ACTION_STUDIO_RUNTIME_STAGE = 'G2.5.2';",
  `    window.__ACTION_STUDIO_BUNDLE_VERSION = '${bundleVersion}';`,
  '    const actionStudioParams = new URLSearchParams(location.search);',
  "    if (location.protocol === 'file:') {",
  "      window.__ACTION_STUDIO_ENTRY_MODE = 'bundle-file';",
  "      document.documentElement.dataset.actionStudioEntry = 'bundle-file';",
  "      document.getElementById('feelAbControls')?.setAttribute('hidden', '');",
  "      const script = document.createElement('script');",
  "      script.src = './action-studio.bundle.js';",
  "      script.dataset.actionStudioVersion = window.__ACTION_STUDIO_BUNDLE_VERSION;",
  '      document.body.appendChild(script);',
  "    } else if (actionStudioParams.get('g252') === '1') {",
  "      window.__ACTION_STUDIO_ENTRY_MODE = 'module';",
  "      document.documentElement.dataset.actionStudioEntry = 'module';",
  "      import('./action-studio.js').then(() => import('./action-studio-runtime-parity.js'));",
  '    } else {',
  "      window.__ACTION_STUDIO_ENTRY_MODE = 'bundle-http';",
  "      document.documentElement.dataset.actionStudioEntry = 'bundle-http';",
  "      const script = document.createElement('script');",
  `      script.src = './action-studio.bundle.js?v=${bundleVersion}';`,
  "      script.dataset.actionStudioVersion = window.__ACTION_STUDIO_BUNDLE_VERSION;",
  '      script.onload = async () => {',
  "        document.documentElement.dataset.actionStudioBoot = 'pass';",
  "        if (actionStudioParams.get('pagesGuardGate') !== '1') return;",
  '        const root = document.documentElement;',
  '        try {',
  '          const runtime = window.__ACTION_STUDIO_GUARD_RUNTIME__;',
  "          if (!runtime?.sampleAt) throw new Error('Guard Runtime deterministic sampler unavailable after bundle boot');",
  "          const result = await runtime.sampleAt('parry', 820);",
  '          const report = result?.report || runtime.report || {};',
  "          const state = String(result?.snapshot?.state || runtime.snapshot?.state || '');",
  "          const clipId = String(report.clipId || '');",
  '          const sourceMs = Math.round((Number(report.sourceTimeSeconds) || 0) * 1000);',
  "          const pass = state === 'guard_parry'",
  "            && runtime.mode === 'parry'",
  "            && clipId === 'SKYRIM_GUARD/power_parry_g363'",
  '            && sourceMs >= 810',
  '            && sourceMs <= 830;',
  "          root.dataset.pagesGuardGate = pass ? 'pass' : 'fail';",
  '          root.dataset.pagesGuardState = state;',
  '          root.dataset.pagesGuardClip = clipId;',
  '          root.dataset.pagesGuardSourceMs = String(sourceMs);',
  '        } catch (error) {',
  "          root.dataset.pagesGuardGate = 'fail';",
  "          root.dataset.pagesGuardError = String(error?.message || error);",
  '        }',
  '      };',
  '      script.onerror = () => {',
  "        document.documentElement.dataset.actionStudioBoot = 'fail';",
  '      };',
  '      document.body.appendChild(script);',
  '    }',
  '  </script>',
].join('\n');
const standaloneHtml = htmlTemplate.replace(moduleEntry, protocolAwareEntry);
await writeFile(htmlOutputFile, standaloneHtml, 'utf8');
console.log(`Built ${normalizedRelativePath(outputFile)} from ${moduleIds.size} ES modules (${output.length} bytes).`);
console.log(`Built ${normalizedRelativePath(htmlOutputFile)} from ${normalizedRelativePath(htmlTemplateFile)} · HTTP bundle ${bundleVersion}.`);
