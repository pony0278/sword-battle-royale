// Generates tools/action-studio/probe.lab.html from the published lab page.
//
// The two pages were 96% identical and hand-synced, which went exactly as hand-syncing does: the
// probe's legend drifted several stages behind, its touch pad was missing the buttons the lab had
// grown, and every layout change this repo made had to be made twice. Worse, the probe copy is
// gitignored, so the drift was invisible - local verification was measuring a page that did not
// exist in the repository.
//
// So it is generated now, and the only difference is the one that has a reason: the published page
// loads Three.js from a CDN, and a sandbox or CI runner with no egress cannot. Everything else -
// markup, styles, legend, script tag version - comes from the real page by construction.
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = new URL('../tools/action-studio/shield-driven-contact-coupling-lab.html', import.meta.url);
const TARGET = new URL('../tools/action-studio/probe.lab.html', import.meta.url);

// Each rewrite must match exactly once. A CDN tag that changed shape silently producing a page with
// no Three.js at all is the failure this guards against - it would look like a lab that hangs.
const REWRITES = [
  [
    '<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>',
    '<script src="/node_modules/three/build/three.min.js"></script>',
  ],
  [
    '<script src="https://cdn.jsdelivr.net/npm/three@0.128.0/examples/js/loaders/GLTFLoader.js"></script>',
    '<script src="/node_modules/three/examples/js/loaders/GLTFLoader.js"></script>',
  ],
];

const BANNER = `<!-- Generated by build/build-probe-lab.mjs from shield-driven-contact-coupling-lab.html.
     Do not edit: it is rebuilt before every browser gate. Change the lab page instead. -->
`;

const source = readFileSync(SOURCE, 'utf8');
let output = source;
for (const [from, to] of REWRITES) {
  const occurrences = output.split(from).length - 1;
  if (occurrences !== 1) {
    throw new Error(`build-probe-lab expected exactly one occurrence of ${from.slice(0, 60)}…, found ${occurrences}`);
  }
  output = output.replace(from, to);
}
if (output.includes('https://cdn')) {
  throw new Error('build-probe-lab left a CDN reference behind; a sandbox with no egress cannot boot this page');
}
writeFileSync(TARGET, BANNER + output);
console.log(`probe.lab.html generated from ${SOURCE.pathname.split('/').pop()} (${output.split('\n').length} lines)`);
