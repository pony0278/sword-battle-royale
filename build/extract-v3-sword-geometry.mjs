import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = path.join(repositoryRoot, 'tools', 'kaykit_combat_lab_v3_procedural_character_generator.html');
const outputFile = path.join(repositoryRoot, 'src', 'character', 'v3-sword-geometry-definition.js');

function readEmbeddedObject(source, id) {
  const embedStart = source.indexOf('const EMBED=');
  const marker = source.indexOf(`${id}:`, embedStart);
  const start = source.indexOf('{', marker);
  if (embedStart < 0 || marker < 0 || start < 0) throw new Error(`Missing embedded object: ${id}`);
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let index = start; index < source.length; index += 1) {
    const character = source[index];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === '{') depth += 1;
    else if (character === '}' && --depth === 0) return JSON.parse(source.slice(start, index + 1));
  }
  throw new Error(`Unterminated embedded object: ${id}`);
}

const componentReaders = Object.freeze({
  5120: { bytes: 1, read: (buffer, offset) => buffer.readInt8(offset) },
  5121: { bytes: 1, read: (buffer, offset) => buffer.readUInt8(offset) },
  5122: { bytes: 2, read: (buffer, offset) => buffer.readInt16LE(offset) },
  5123: { bytes: 2, read: (buffer, offset) => buffer.readUInt16LE(offset) },
  5125: { bytes: 4, read: (buffer, offset) => buffer.readUInt32LE(offset) },
  5126: { bytes: 4, read: (buffer, offset) => buffer.readFloatLE(offset) },
});

const typeSizes = Object.freeze({ SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4, MAT4: 16 });

function decodeBuffer(uri) {
  const match = String(uri || '').match(/^data:[^,]+;base64,(.+)$/);
  if (!match) throw new Error('V3 sword buffer must be an embedded base64 data URI');
  return Buffer.from(match[1], 'base64');
}

function readAccessor(gltf, buffers, accessorIndex) {
  const accessor = gltf.accessors[accessorIndex];
  const view = gltf.bufferViews[accessor.bufferView];
  const reader = componentReaders[accessor.componentType];
  const size = typeSizes[accessor.type];
  if (!reader || !size) throw new Error(`Unsupported accessor ${accessor.componentType}/${accessor.type}`);
  const buffer = buffers[view.buffer || 0];
  const start = (view.byteOffset || 0) + (accessor.byteOffset || 0);
  const elementBytes = reader.bytes * size;
  const stride = view.byteStride || elementBytes;
  const values = [];
  for (let element = 0; element < accessor.count; element += 1) {
    const elementStart = start + element * stride;
    for (let component = 0; component < size; component += 1) {
      values.push(reader.read(buffer, elementStart + component * reader.bytes));
    }
  }
  return values;
}

function boundsOf(positions) {
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (let index = 0; index < positions.length; index += 3) {
    for (let axis = 0; axis < 3; axis += 1) {
      min[axis] = Math.min(min[axis], positions[index + axis]);
      max[axis] = Math.max(max[axis], positions[index + axis]);
    }
  }
  return { min, max };
}

function generatedModule(definition) {
  return `// Generated by build/extract-v3-sword-geometry.mjs. Do not edit by hand.\n`
    + `function deepFreeze(value) {\n`
    + `  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n`
    + `  Object.values(value).forEach(deepFreeze);\n`
    + `  return Object.freeze(value);\n`
    + `}\n\n`
    + `export const V3_SWORD_GEOMETRY_DEFINITION = deepFreeze(${JSON.stringify(definition, null, 2)});\n`;
}

const source = await readFile(sourceFile, 'utf8');
const gltf = readEmbeddedObject(source, 'sword');
const scene = gltf.scenes[gltf.scene || 0];
const sourceNode = gltf.nodes[scene.nodes[0]];
const sourceMesh = gltf.meshes[sourceNode.mesh];
if (!sourceMesh || sourceMesh.primitives.length !== 1) throw new Error('Expected one v3 sword mesh primitive');
const primitive = sourceMesh.primitives[0];
if ((primitive.mode ?? 4) !== 4) throw new Error('Expected triangle-list v3 sword geometry');
const buffers = gltf.buffers.map((entry) => decodeBuffer(entry.uri));
const sourcePositions = readAccessor(gltf, buffers, primitive.attributes.POSITION);
const positions = [];
for (let index = 0; index < sourcePositions.length; index += 3) {
  positions.push(-sourcePositions[index], -sourcePositions[index + 1], sourcePositions[index + 2]);
}
const indices = readAccessor(gltf, buffers, primitive.indices);
const tipY = -Math.max(...sourcePositions.filter((_, index) => index % 3 === 1));
const guardHalfWidth = Math.max(...sourcePositions.filter((_, index) => index % 3 === 0).map(Math.abs));
const bladeMidY = -0.85;
const definition = {
  format: 'procedural-v3-sword-source-geometry',
  version: 1,
  id: 'v3_sword_1handed_exact_edges',
  source: 'tools/kaykit_combat_lab_v3_procedural_character_generator.html#EMBED.sword',
  sourceObject: sourceNode.name || sourceMesh.name || 'sword_1handed',
  coordinateTransform: 'rotate-z-pi-for-action-studio-hand-r-mount',
  vertexCount: positions.length / 3,
  triangleCount: indices.length / 3,
  bounds: boundsOf(positions),
  positions,
  indices,
  rigNodes: [
    { id: 'weapon.root', parent: null, position: [0, 0, 0] },
    { id: 'pommel', parent: 'weapon.root', position: [0, 0.275, 0] },
    { id: 'grip', parent: 'weapon.root', position: [0, 0.055, 0] },
    { id: 'secondary_grip', parent: 'grip', position: [0, 0.08, 0] },
    { id: 'guard', parent: 'weapon.root', position: [0, -0.20, 0] },
    { id: 'guard.l', parent: 'guard', position: [guardHalfWidth, 0, 0] },
    { id: 'guard.r', parent: 'guard', position: [-guardHalfWidth, 0, 0] },
    { id: 'blade.root', parent: 'guard', position: [0, -0.10, 0] },
    { id: 'blade.mid', parent: 'blade.root', position: [0, bladeMidY + 0.30, 0] },
    { id: 'parry.point', parent: 'blade.mid', position: [0, 0.15, 0] },
    { id: 'blade.tip', parent: 'blade.mid', position: [0, tipY - bladeMidY, 0] },
  ],
};

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, generatedModule(definition), 'utf8');
console.log(`Generated ${path.relative(repositoryRoot, outputFile)} (${definition.vertexCount} vertices, ${definition.triangleCount} triangles).`);
